/* ============================================================
   InputRestoreGuard — страховка от «залипшего» ввода Phaser.
   Оверлеи-каталоги экипировки (шлем/меч/щит/кольцо/ботинки/броня)
   при открытии делают scene.input.enabled = false и должны вернуть
   его при закрытии. На некоторых путях навигации ввод оставался
   выключенным → кнопки сцены (магазин/задания/бой) переставали
   нажиматься, хотя HTML-меню снизу работало.

   Все эти каталоги — и ТОЛЬКО они — выключают ввод, и все имеют класс
   .wd-overlay. Значит правило простое и безопасное: если на экране НЕТ
   ни одного .wd-overlay — ввод Phaser обязан быть включён. Сторож это
   гарантирует (самовосстановление за ~0.5с на любом пути навигации).
   ============================================================ */
(() => {
  'use strict';
  function tick() {
    try {
      if (document.querySelector('.wd-overlay')) return;  // каталог открыт — ввод off корректно
      const g = window.game;
      if (!g || !g.scene || !g.scene.getScenes) return;
      g.scene.getScenes(true).forEach((s) => {
        if (s && s.input && s.input.enabled === false) {
          try { s.input.enabled = true; } catch (_) {}
        }
      });
    } catch (_) {}
  }
  setInterval(tick, 500);
})();
